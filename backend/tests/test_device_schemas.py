import uuid

import pytest
from pydantic import ValidationError

from app.core.enums import Criticality, DeviceStatus
from app.schemas.catalog import DeviceModelUpdate
from app.schemas.device import DeviceCreate, DeviceUpdate
from app.schemas.structure import HospitalUpdate, LocationCreate, LocationUpdate

U = uuid.uuid4
BASE = dict(hospital_id=U(), department_id=U(), device_model_id=U(), device_code=" DEV-1 ", name="  Ventilator ")


def test_device_create_defaults_and_trimming():
    d = DeviceCreate(**BASE)
    assert d.device_code == "DEV-1" and d.name == "Ventilator"
    assert d.status == DeviceStatus.ACTIVE and d.criticality == Criticality.MEDIUM
    assert d.qr_identifier is None  # generated by the service


@pytest.mark.parametrize("bad", [dict(status="deleted"), dict(criticality="urgent"), dict(device_code="  "), dict(name="")])
def test_device_create_rejects_bad_values(bad):
    with pytest.raises(ValidationError):
        DeviceCreate(**{**BASE, **bad})


def test_update_cannot_move_hospital_or_null_required_fields():
    with pytest.raises(ValidationError):
        DeviceUpdate(hospital_id=U())
    for field in ("name", "department_id", "device_code", "status"):
        with pytest.raises(ValidationError):
            DeviceUpdate(**{field: None})
    assert DeviceUpdate(location_id=None).model_dump(exclude_unset=True) == {"location_id": None}  # detach is allowed


def test_other_patch_schemas_reject_nulls():
    with pytest.raises(ValidationError):
        HospitalUpdate(is_active=None)
    with pytest.raises(ValidationError):
        DeviceModelUpdate(name=None)
    assert HospitalUpdate(address=None).model_dump(exclude_unset=True) == {"address": None}


def test_location_needs_something():
    with pytest.raises(ValidationError):
        LocationCreate(hospital_id=U(), building="  ", floor=None, room="")
    assert LocationCreate(hospital_id=U(), room="204").room == "204"


def test_qr_identifier_validation():
    valid_qrs = ["IMD-A3B7C9D2", "DEV_001", "DEV.001"]
    invalid_qrs = ["DEV/001", "DEV 001", "   ", "DEV?001"]

    for qr in valid_qrs:
        device = DeviceCreate(**{**BASE, "qr_identifier": qr})
        assert device.qr_identifier == qr

        update = DeviceUpdate(qr_identifier=qr)
        assert update.qr_identifier == qr

    for qr in invalid_qrs:
        with pytest.raises(ValidationError):
            DeviceCreate(**{**BASE, "qr_identifier": qr})

        with pytest.raises(ValidationError):
            DeviceUpdate(qr_identifier=qr)



def test_qr_identifier_normalization():
    device = DeviceCreate(
        **{**BASE, "qr_identifier": "imd-abc123"}
    )
    assert device.qr_identifier == "IMD-ABC123"

    update = DeviceUpdate(qr_identifier="dev_001")
    assert update.qr_identifier == "DEV_001"


def test_decommissioned_only_through_archive():
    with pytest.raises(ValidationError):
        DeviceCreate(**{**BASE, "status": "decommissioned"})

    with pytest.raises(ValidationError):
        DeviceUpdate(status="decommissioned")


def test_location_fields_cleaning():
    location = LocationCreate(
        hospital_id=U(),
        building="  Main Building  ",
        floor="  2  ",
        room="  204  "
    )

    assert location.building == "Main Building"
    assert location.floor == "2"
    assert location.room == "204"

    update = LocationUpdate(
        building="  Building A  ",
        floor="   "
    )

    assert update.building == "Building A"
    assert update.floor is None

    with pytest.raises(ValidationError):
        LocationCreate(
            hospital_id=U(),
            building="   ",
            floor="   ",
            room="   "
        )